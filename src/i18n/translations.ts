export function translateStatus(t: TranslationKeys, status: string): string {
  switch (status) {
    case 'Open':
      return t.statusOpen;
    case 'Under Review':
      return t.statusUnderReview;
    case 'Assigned':
      return t.statusAssigned;
    case 'In Progress':
      return t.statusInProgress;
    case 'Resolved':
      return t.statusResolved;
    case 'Rejected':
      return t.statusRejected;
    default:
      return status;
  }
}

export function translateCategory(t: TranslationKeys, category: string): string {
  switch (category) {
    case 'Roads':
      return t.catRoads;
    case 'Waste Management':
      return t.catWaste;
    case 'Water Supply':
      return t.catWater;
    case 'Electricity':
      return t.catElectricity;
    case 'Trees':
      return t.catTrees;
    case 'Drainage':
      return t.catDrainage;
    case 'Public Safety':
      return t.catSafety;
    case 'Other':
      return t.catOther;
    default:
      return category;
  }
}

export function translateSeverity(t: TranslationKeys, severity: string): string {
  switch (severity.toUpperCase()) {
    case 'CRITICAL':
      return t.severityCritical;
    case 'HIGH':
      return t.severityHigh;
    case 'MEDIUM':
      return t.severityMedium;
    case 'LOW':
      return t.severityLow;
    default:
      return severity;
  }
}

